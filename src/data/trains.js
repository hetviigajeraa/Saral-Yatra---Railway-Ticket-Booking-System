// Get trains by route — returns all if no match (demo fallback)
export function getTrainsByRoute(fromCode, toCode) {
  const matched = trains.filter(
    (t) => t.fromCode === fromCode && t.toCode === toCode
  );
  return matched.length > 0 ? matched : trains;
}

// Get a single train
export function getTrainById(id) {
  return trains.find((t) => t.id === id);
}

